<#
  check: verifies the built site and runs every "check it in 30 seconds" snippet exactly as a reader would.
    powershell -NoProfile -ExecutionPolicy Bypass -File .\check.ps1 [-SkipClaude] [-SkipSlow]
  Each snippet (checks\<id>.ps1, generated by build.py) must end with REPRODUCED on the author's machine.
  -SkipClaude skips the snippets that call claude (t14, h01, h02, h03); -SkipSlow skips t13.
  Exit 0 = all good. ASCII-only file.
#>
param([switch]$SkipClaude, [switch]$SkipSlow)
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$bad = 0

& python (Join-Path $here 'check_links.py')
if ($LASTEXITCODE -ne 0) { $bad++ }

# run the snippets under this Windows' default console code page, as a reader's fresh window would
# (the Claude Code Bash tool and some terminals use 65001, which hides t05 and t09)
$oem = [System.Globalization.CultureInfo]::CurrentCulture.TextInfo.OEMCodePage
$savedEnc = [Console]::OutputEncoding
[Console]::OutputEncoding = [System.Text.Encoding]::GetEncoding($oem)
$claudeIds = @('t14', 'h01', 'h02', 'h03')
$rows = @()
foreach ($f in (Get-ChildItem -LiteralPath (Join-Path $here 'checks') -Filter '*.ps1' | Sort-Object Name)) {
    $id = $f.BaseName
    if ($SkipClaude -and ($claudeIds -contains $id)) { $rows += [pscustomobject]@{ Id = $id; Result = 'SKIPPED'; Detail = '-SkipClaude' }; continue }
    if ($SkipSlow -and $id -eq 't13') { $rows += [pscustomobject]@{ Id = $id; Result = 'SKIPPED'; Detail = '-SkipSlow' }; continue }
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $out = @(& powershell.exe -NoProfile -ExecutionPolicy Bypass -File $f.FullName 2>$null | ForEach-Object { [string]$_ } | Where-Object { $_.Trim() -ne '' })
    $sw.Stop()
    $last = ''
    if ($out.Count -gt 0) { $last = $out[$out.Count - 1].Trim() }
    $detail = ''
    if ($out.Count -gt 1) { $detail = $out[$out.Count - 2].Trim() }
    if ($detail.Length -gt 70) { $detail = $detail.Substring(0, 70) }
    $rows += [pscustomobject]@{ Id = $id; Result = $last; Detail = ($detail + ' (' + [int]$sw.Elapsed.TotalSeconds + ' s)') }
    if ($last -ne 'REPRODUCED') { $bad++ }
}
[Console]::OutputEncoding = $savedEnc

$rows | Format-Table -AutoSize | Out-String -Width 160
if ($bad -eq 0) { 'ALL GOOD' } else { "$bad problem(s)" }
exit $(if ($bad -eq 0) { 0 } else { 1 })
